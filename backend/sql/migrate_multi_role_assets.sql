USE billing_rwnet;
CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(200) NOT NULL,
  role ENUM('superadmin','admin','kolektor') NOT NULL DEFAULT 'kolektor',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS app_settings (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  brand_name VARCHAR(120) NOT NULL DEFAULT 'BillingNet',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
INSERT IGNORE INTO app_settings (id,brand_name) VALUES (1,'BillingNet');
CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  description VARCHAR(200) NOT NULL, category VARCHAR(100) NOT NULL DEFAULT 'Lainnya',
  amount DECIMAL(12,2) NOT NULL, expense_date DATE NOT NULL,
  payment_method ENUM('cash','transfer') NOT NULL DEFAULT 'cash',
  notes TEXT NULL, created_by VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_expense_date (expense_date)
);
CREATE TABLE IF NOT EXISTS assets (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  asset_type ENUM('ont','other') NOT NULL DEFAULT 'other', name VARCHAR(150) NOT NULL,
  serial_number VARCHAR(150) NOT NULL UNIQUE, brand VARCHAR(100) NULL, model VARCHAR(100) NULL,
  quantity INT UNSIGNED NOT NULL DEFAULT 1,
  condition_status ENUM('baik','rusak','perbaikan') NOT NULL DEFAULT 'baik',
  location VARCHAR(200) NULL, notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
